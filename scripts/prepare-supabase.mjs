import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import ts from "typescript";

// Turn the application's static tagged queries into a reviewed server-only
// allowlist. The RPC accepts an ID plus values, never SQL from a request.
const queries = new Map();
function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) { walk(file); continue; }
    if (!/\.tsx?$/.test(file)) continue;
    const tree = ts.createSourceFile(file, fs.readFileSync(file, "utf8"), ts.ScriptTarget.Latest, true);
    const visit = (node) => {
      if (ts.isTaggedTemplateExpression(node) && /^(database\(\)|sql)$/.test(node.tag.getText(tree))) {
        const t = node.template;
        const parts = ts.isNoSubstitutionTemplateLiteral(t) ? [t.text] : [t.head.text, ...t.templateSpans.map(span => span.literal.text)];
        const normalized = parts.map(part => part.replace(/\r\n/g, "\n"));
        const id = crypto.createHash("sha256").update(JSON.stringify(normalized)).digest("hex");
        const returns = /\bSELECT\b|\bRETURNING\b/i.test(normalized.join(""));
        queries.set(id, { parts: normalized, returns, file });
      }
      ts.forEachChild(node, visit);
    };
    visit(tree);
  }
}
walk("app"); walk("lib");
let sql = fs.readFileSync("supabase/transition_base.sql", "utf8");
sql += `\n-- Generated by npm run db:prepare. Review and run this complete file.\nCREATE OR REPLACE FUNCTION public.sims_query(query_id text, query_values jsonb)\nRETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path = 'public' AS $fn$\nDECLARE parts jsonb; returns_rows boolean; statement text := ''; result jsonb := '[]'::jsonb; row_data record; i integer;\nBEGIN\n  CASE query_id\n`;
for (const [id, query] of [...queries].sort()) {
  const literal = JSON.stringify(query.parts).replaceAll("'", "''");
  sql += `    -- ${query.file.replaceAll("\\", "/")}\n    WHEN '${id}' THEN parts := '${literal}'::jsonb; returns_rows := ${query.returns};\n`;
}
sql += `    ELSE RAISE EXCEPTION 'Unknown application query';\n  END CASE;\n  IF jsonb_typeof(query_values) <> 'array' OR jsonb_array_length(query_values) <> jsonb_array_length(parts)-1 THEN\n    RAISE EXCEPTION 'Invalid query parameters';\n  END IF;\n  FOR i IN 0..jsonb_array_length(parts)-1 LOOP\n    statement := statement || (parts->>i);\n    IF i < jsonb_array_length(query_values) THEN\n      -- Quote each input once, independently; never replace text in a value.\n      statement := statement || quote_nullable(query_values->>i);\n    END IF;\n  END LOOP;\n  IF returns_rows THEN\n    FOR row_data IN EXECUTE statement LOOP result := result || jsonb_build_array(to_jsonb(row_data)); END LOOP;\n  ELSE EXECUTE statement;\n  END IF;\n  RETURN result;\nEND $fn$;\nREVOKE ALL ON FUNCTION public.sims_query(text,jsonb) FROM PUBLIC, anon, authenticated;\nGRANT EXECUTE ON FUNCTION public.sims_query(text,jsonb) TO service_role;\nNOTIFY pgrst, 'reload schema';\n`;
fs.writeFileSync("supabase/transition_setup.sql", sql);
console.log(`Prepared Supabase transition with ${queries.size} static queries. No remote changes made.`);
