import fs from 'node:fs';
const version=process.argv[2];
if(!/^\d+\.\d+\.\d+\+[1-9]\d*$/.test(version||''))throw new Error('Use a version such as 1.0.1+4.');
const [name,code]=version.split('+');
const pubspec='app_inventory/pubspec.yaml';const original=fs.readFileSync(pubspec,'utf8');
const previous=original.match(/^version:\s*\S+\+(\d+)\s*$/m);
if(previous&&Number(code)<=Number(previous[1]))throw new Error('Every update must increase the Android build number.');
fs.writeFileSync(pubspec,original.replace(/^version:.*$/m,'version: '+version));
fs.writeFileSync('app_inventory/lib/core/release_info.dart',`// Generated by scripts/set-app-version.mjs.\nconst appVersion = '${name}';\nconst appBuildNumber = ${Number(code)};\n`);
console.log('Application version set to '+version+'.');
